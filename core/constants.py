"""项目级共享常量。

集中定义此前散落在各处的魔法值，避免同一配置在多个地方出现不同默认值。
所有模块（含 utils.config 与 ui.settings_dialog）都应从这里取值，
不再就地硬编码。
"""

# ---------------------------------------------------------------- 漂移检测

# 角色漂移（OOC）判定阈值（余弦相似度）。
#
# 按 bge-small-zh-v1.5 实测校准（2026-08）：锚点取「人设 + 口头禅 + 台词」时，
#   - 人设内回复        约 0.53 ~ 0.59
#   - 明显偏离的回复    约 0.43 ~ 0.53
# 取 0.52 是「宁可漏检，也不误伤正常回复」的取向 —— OOC 重试一次会拖慢回复，
# 而误把正常回复判成 OOC 的代价更高。
#
# 该值此前在 7 处分别硬编码为 0.52 / 0.58 / 0.72 / 0.75，现统一以此为准。
DEFAULT_DRIFT_THRESHOLD = 0.52

# OOC 判定时允许的最大重写重试次数。
DEFAULT_MAX_OOC_RETRIES = 1

# ---------------------------------------------------------------- LLM 默认

# 默认上下文窗口（token）。ds-v4 系列可支持到 1M，上限 2M。
DEFAULT_CONTEXT_WINDOW = 1048576

# 默认云端模型（OpenAI 兼容，DeepSeek）。
DEFAULT_OPENAI_MODEL = "deepseek-v4-flash"

# HuggingFace 镜像端点（国内网络建议，留空则用官方源）。
DEFAULT_HF_ENDPOINT = "https://hf-mirror.com"

# ---------------------------------------------------------------- 其他

# 用户多久未说话视为「空闲」（分钟），用于主动搭话判定。
DEFAULT_IDLE_MINUTES = 15

# TTS 默认关闭：绝大多数用户并未部署 GPT-SoVITS 服务，
# 默认开启会让程序每次回复都去尝试连接本地端口。
DEFAULT_TTS_ENABLED = False
